def test_entirely_covered_plan_has_no_plan_object_rows(
    session: Session, repealing_plan: models.Plan
) -> None:
    """Ryhti allows no plan object cancellation infos on a whole plan."""
    repealing_plan.geom = area(0, 0, SIDE, SIDE)
    session.commit()

    infos = cancellation_infos(session, repealing_plan)

    assert len(infos) == 1
    assert infos[0].cancels_entire_plan is True
    assert repealed_objects(session, infos[0]) == {}


def test_only_touching_plan_is_not_repealed(
    session: Session, repealing_plan: models.Plan
) -> None:
    """A plan that shares only a border with the repealing plan stays valid."""
    repealing_plan.geom = area(SIDE, 0, SIDE + MIDDLE, SIDE)
    session.commit()

    assert cancellation_infos(session, repealing_plan) == []


def test_plan_of_another_level_1_plan_type_is_not_repealed(
    session: Session,
    repealing_plan: models.Plan,
    repealing_plan_matter: models.PlanMatter,
) -> None:
    """A repealing plan only repeals plans of its own level 1 plan type."""
    repealing_plan_matter.plan_type = codes.PlanType(value="3", level=1, status="LOCAL")
    session.commit()
    # The plan matter carries the plan type, so the plan is written again to
    # make the trigger read it.
    repealing_plan.geom = area(0, 0, MIDDLE, SIDE - 1)
    session.commit()

    assert cancellation_infos(session, repealing_plan) == []


def test_plan_of_the_same_plan_matter_is_not_repealed(
    session: Session,
    cancelled_plan: models.Plan,
    plan_matter_instance: models.PlanMatter,
    preparation_status_instance: codes.LifeCycleStatus,
) -> None:
    """A plan does not repeal the earlier phases of its own plan matter."""
    plan_matter_instance.repealing = True
    session.commit()

    plan = models.Plan(
        id=str(uuid.uuid4()),
        plan_matter=plan_matter_instance,
        name={"fin": "Saman kaava-asian kaava"},
        geom=area(0, 0, MIDDLE, SIDE),
        lifecycle_status=preparation_status_instance,
    )
    session.add(plan)
    session.commit()

    assert cancellation_infos(session, plan) == []
    assert cancelled_plan.id is not None


def test_plan_that_is_not_final_is_not_repealed(
    session: Session, repealing_plan: models.Plan, cancelled_plan: models.Plan
) -> None:
    """Only the plans of hame.plan_valid are repealed."""
    cancelled_plan.final = False
    session.commit()
    repealing_plan.geom = area(0, 0, MIDDLE, SIDE - 1)
    session.commit()

    assert cancellation_infos(session, repealing_plan) == []


def test_repealing_flag_fills_and_clears_the_cancellation_info(
    session: Session,
    repealing_plan: models.Plan,
    repealing_plan_matter: models.PlanMatter,
) -> None:
    """Unsetting the flag on the plan matter removes the rows again."""
    assert len(cancellation_infos(session, repealing_plan)) == 1

    repealing_plan_matter.repealing = False
    session.commit()

    assert cancellation_infos(session, repealing_plan) == []

    repealing_plan_matter.repealing = True
    session.commit()

    assert len(cancellation_infos(session, repealing_plan)) == 1


def test_moving_the_repealing_plan_away_clears_the_cancellation_info(
    session: Session, repealing_plan: models.Plan
) -> None:
    repealing_plan.geom = area(2 * SIDE, 0, 3 * SIDE, SIDE)
    session.commit()

    assert cancellation_infos(session, repealing_plan) == []


def test_plan_that_stays_repealed_keeps_its_cancellation_info_id(
    session: Session, repealing_plan: models.Plan
) -> None:
    """The rows are upserted, so rows added under them by hand survive."""
    original_id = cancellation_infos(session, repealing_plan)[0].id

    repealing_plan.geom = area(0, 0, MIDDLE, SIDE - 1)
    session.commit()

    assert cancellation_infos(session, repealing_plan)[0].id == original_id
