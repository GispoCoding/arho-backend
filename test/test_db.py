def table_privileges(
    db_connection: Connection, schema: str, table: str, role: str
) -> set[str]:
    cur = db_connection.execute(
        "SELECT privilege_type "
        "FROM information_schema.role_table_grants "
        "WHERE "
        "  table_schema = %s "
        "  AND table_name = %s "
        "  AND grantee = %s",
        (schema, table, role),
    )
    return {row[0] for row in cur}


@pytest.mark.parametrize("table_name", hame_tables())
def test_read_only_role_privileges_on_hame_tables(
    db_connection: Connection, table_name: str
) -> None:
    privileges = table_privileges(db_connection, "hame", table_name, ROLE_READ_ONLY)
    assert "SELECT" in privileges
    assert "INSERT" not in privileges
    assert "UPDATE" not in privileges
    assert "DELETE" not in privileges


