def foreign_keys() -> list[tuple[str, str, str]]:
    return [
        (table.schema, table.name, column.name)
        for table in Base.metadata.tables.values()
        for column in table.columns
        if table.schema in {"hame", "codes"} and column.foreign_keys
    ]


@pytest.mark.skip
@pytest.mark.parametrize(("table_schema", "table_name", "column_name"), foreign_keys())
def test_each_foreign_key_has_an_index(
    db_connection: Connection, table_schema: str, table_name: str, column_name: str
) -> None:
    with db_connection.cursor() as cur:
        cur.execute(
            "SELECT indexname "
            "FROM pg_indexes "
            "WHERE schemaname = %s "
            "  AND tablename = %s "
            "  AND indexdef LIKE %s;",
            (table_schema, table_name, f"%({column_name})%"),
        )
        indexes = cur.fetchall()
        assert indexes, (
            f"No index found for foreign key {table_schema}.{table_name}.{column_name}"
        )


def geom_columns() -> list[tuple[str, str, str]]:
    return [
        (table.schema, table.name, column.name)
        for table in Base.metadata.tables.values()
        for column in table.columns
        if table.schema in {"hame", "codes"} and column.name == "geom"
    ]


@pytest.mark.parametrize(("table_schema", "table_name", "column_name"), geom_columns())
def test_all_geometry_columns_have_a_spatial_index(
    db_connection: Connection, table_schema: str, table_name: str, column_name: str
) -> None:
    with db_connection.cursor() as cur:
        cur.execute(
            "SELECT indexname "
            "FROM pg_indexes "
            "WHERE schemaname = %s "
            "  AND tablename = %s "
            "  AND indexdef LIKE %s;",
            (table_schema, table_name, f"%USING gist ({column_name})%"),
        )
        indexes = cur.fetchall()
        assert indexes, (
            f"No spatial index found for geometry column {table_schema}.{table_name}.{column_name}"
        )
