def test_schemas_exists(db_connection: Connection) -> None:
    with db_connection.cursor() as cur:
        cur.execute(
            "SELECT schema_name FROM information_schema.schemata "
            "WHERE schema_name IN ('hame', 'codes') ORDER BY schema_name DESC"
        )
        assert cur.fetchall() == [("hame",), ("codes",)]


